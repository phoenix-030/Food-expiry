/**
 * Intelligent Image Resolver
 * @param {string} productName - name of product (e.g. "Amul Butter", "Fresh Red Tomato")
 * @param {string} category - category ("Vegetables", "Dairy", "Fruits", etc.)
 * @param {string} customUrl - explicit image URL (e.g. from Open Food Facts)
 * @returns {string} High-resolution image URL
 */
export const getProductImage = (productName = '', category = 'Other', customUrl = '') => {
  if (customUrl && typeof customUrl === 'string' && customUrl.startsWith('http')) {
    return customUrl;
  }

  const nameKey = String(productName).toLowerCase().replace(/[^a-z0-9]/g, '');

  // 1. Check specific Vegetable matches
  for (const [key, url] of Object.entries(VEGETABLE_IMAGES)) {
    if (key !== 'default_vegetable' && nameKey.includes(key)) {
      return url;
    }
  }

  // 2. Check specific Dairy matches
  for (const [key, url] of Object.entries(DAIRY_IMAGES)) {
    if (key !== 'default_dairy' && nameKey.includes(key)) {
      return url;
    }
  }

  // 3. Fallback to category default
  return CATEGORY_DEFAULTS[category] || CATEGORY_DEFAULTS.Other;
};

